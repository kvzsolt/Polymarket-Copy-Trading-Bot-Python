"""Release-gate invariant — production code never imports legacy or probe modules.

Static AST scan over every production package root. Fails fast if anything
under those roots imports:

* the ``legacy`` package (still present, but tests-only),
* any of the deleted root probe scripts (``test_probe*``, ``test_doctor_*``).

Also asserts the deleted probe scripts no longer exist at repo root.
"""
from __future__ import annotations

import ast
from pathlib import Path

import pytest

REPO_ROOT = Path(__file__).resolve().parents[2]

PRODUCTION_ROOTS: tuple[str, ...] = (
    "bootstrap.py",
    "app.py",
    "bot.py",
    "bot_cli",
    "clients",
    "config",
    "domain",
    "integrations",
    "interfaces",
    "orchestrators",
    "scripts",
    "services",
    "storage",
    "utils",
)

FORBIDDEN_PREFIXES: tuple[str, ...] = (
    "legacy",
    "test_probe",
    "test_doctor",
    # issue-78: redemption pipeline removed; NearOneExitService replaces it.
    "services.redemption",
    "services.redemptionService",
    "services.autoRedeem",
)

DELETED_PROBE_FILES: tuple[str, ...] = (
    "test_probe.py",
    "test_probe2.py",
    "test_probe3.py",
    "test_probe4.py",
    "test_probe5.py",
    "test_probe6.py",
    "test_doctor_detect.py",
    "test_doctor_gnosis.py",
)


def _iter_production_python_files() -> list[Path]:
    files: list[Path] = []
    for entry in PRODUCTION_ROOTS:
        path = REPO_ROOT / entry
        if not path.exists():
            continue
        if path.is_file() and path.suffix == ".py":
            files.append(path)
            continue
        for py in path.rglob("*.py"):
            # Skip generated bytecode, hidden dirs, and any nested ``legacy``
            # or ``tests`` subtree that might appear inside a production root.
            parts = set(py.relative_to(REPO_ROOT).parts)
            if "__pycache__" in parts or "tests" in parts or "legacy" in parts:
                continue
            files.append(py)
    return files


def _collect_imports(source: str, file_label: str) -> set[str]:
    try:
        tree = ast.parse(source, filename=file_label)
    except SyntaxError as exc:  # pragma: no cover - surfaces a real bug
        pytest.fail(f"SyntaxError parsing {file_label}: {exc}")
    targets: set[str] = set()
    for node in ast.walk(tree):
        if isinstance(node, ast.Import):
            for alias in node.names:
                targets.add(alias.name)
        elif isinstance(node, ast.ImportFrom):
            # Absolute imports only — relative ImportFrom (level > 0) cannot
            # name top-level legacy/probe modules.
            if node.level == 0 and node.module:
                targets.add(node.module)
    return targets


def _is_forbidden(target: str) -> bool:
    """Return True if any dotted segment of ``target`` matches a forbidden prefix.

    Checking every segment (not just the head) catches nested cases like
    ``scripts.test_probe2`` or ``some.pkg.legacy.foo`` that would slip past a
    head-only check.
    """
    for segment in target.split("."):
        for prefix in FORBIDDEN_PREFIXES:
            if segment == prefix or segment.startswith(prefix):
                return True
    return False


def test_no_production_imports_of_legacy_or_probes() -> None:
    """Walk production packages; fail if any module imports a forbidden target."""
    offenders: list[tuple[str, str]] = []
    for py in _iter_production_python_files():
        rel = str(py.relative_to(REPO_ROOT))
        for target in _collect_imports(py.read_text(encoding="utf-8"), rel):
            if _is_forbidden(target):
                offenders.append((rel, target))
    assert not offenders, (
        "Production modules must not import legacy or probe targets. "
        f"Offenders: {offenders}"
    )


def test_root_probe_scripts_were_deleted() -> None:
    """Issue #77 deleted these — guard against accidental re-introduction."""
    survivors = [
        name for name in DELETED_PROBE_FILES if (REPO_ROOT / name).exists()
    ]
    assert not survivors, (
        "Probe scripts must not exist at repo root. "
        f"Found: {survivors}"
    )


@pytest.mark.parametrize(
    "target",
    [
        "legacy",
        "legacy.tradeExecutor",
        "test_probe",
        "test_probe2",
        "test_probe_new_variant",
        "test_doctor_detect",
        "test_doctor_gnosis",
        "test_doctor_anything_else",
        "scripts.test_probe2",          # nested-segment match (issue #77 PR review)
        "some.pkg.legacy.foo",          # nested-segment match
        "pkg.subpkg.test_doctor_x",     # nested-segment + wildcard match
    ],
)
def test_is_forbidden_matches_wildcard_and_nested(target: str) -> None:
    assert _is_forbidden(target), target


@pytest.mark.parametrize(
    "target",
    [
        "config.app_config",
        "services.executionService",
        "tests.helpers",                # 'tests' is not 'test_'
        "polymarket_legacy_tools",      # head doesn't start with 'legacy'
        "doctor",                        # different prefix
    ],
)
def test_is_forbidden_does_not_overmatch(target: str) -> None:
    assert not _is_forbidden(target), target
