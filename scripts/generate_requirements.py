#!/usr/bin/env python3
"""Generate the pinned requirements exports from the canonical ``uv.lock``.

``uv.lock`` is the single source of truth for dependency resolution. The two
install exports are generated artifacts, never hand-edited:

- ``requirements.txt``         — full dev export (runtime + ``dev`` extra)
- ``requirements.runtime.txt`` — production export (runtime only)

Both are universal (all markers preserved) and hash-free, matching the
convention of the previous ``uv pip compile`` artifacts. ``scripts/
check_requirements_drift.py`` re-renders both files through this module and
fails on any byte difference, so the exports can never silently drift from
the lock.

Regenerate after every ``uv lock``:

    python scripts/generate_requirements.py
"""

from __future__ import annotations

import argparse
import pathlib
import subprocess
import sys

REPO_ROOT = pathlib.Path(__file__).resolve().parent.parent

# Export flags shared by both artifacts:
#   --frozen           never rewrite uv.lock while exporting
#   --no-hashes        pinned names+versions+markers only (previous convention)
#   --no-emit-project  the project itself is installed separately
#                     (Docker: ``pip install --no-deps .``; dev: ``pip install -e .``)
#   --no-header        this module writes the documented header instead
DEV_EXPORT_FLAGS = ("--frozen", "--all-extras", "--no-hashes", "--no-emit-project", "--no-header")
RUNTIME_EXPORT_FLAGS = ("--frozen", "--no-hashes", "--no-emit-project", "--no-header")

DEV_OUTPUT = "requirements.txt"
RUNTIME_OUTPUT = "requirements.runtime.txt"


def _uv_export_command(flags: tuple[str, ...]) -> list[str]:
    return ["uv", "export", *flags]


def _header(flags: tuple[str, ...], output_name: str) -> list[str]:
    command = " ".join(_uv_export_command(flags))
    return [
        "# This file was autogenerated from uv.lock via uv and scripts/generate_requirements.py.",
        f"# Regenerate it with: python scripts/generate_requirements.py (writes {output_name})",
        f"# Underlying command: {command}",
        "# uv.lock is the single source of truth — do not edit this file by hand.",
    ]


def render_export(flags: tuple[str, ...], output_name: str) -> str:
    """Return the exact bytes (as text) of one generated export file.

    Runs ``uv export`` with the documented flags and prepends the generation
    header. The result is deterministic for a given ``uv.lock`` and uv
    version, which is what ``check_requirements_drift`` byte-compares.
    """

    completed = subprocess.run(
        _uv_export_command(flags),
        cwd=REPO_ROOT,
        capture_output=True,
        text=True,
        check=False,
    )
    if completed.returncode != 0:
        raise RuntimeError(
            f"uv export failed (exit {completed.returncode}):\n{completed.stderr.strip()}"
        )
    body = completed.stdout.rstrip("\n") + "\n"
    return "\n".join(_header(flags, output_name)) + "\n" + body


def write_exports(root: pathlib.Path = REPO_ROOT) -> list[pathlib.Path]:
    """(Re)generate both export files and return the paths written."""

    written: list[pathlib.Path] = []
    for flags, name in (
        (DEV_EXPORT_FLAGS, DEV_OUTPUT),
        (RUNTIME_EXPORT_FLAGS, RUNTIME_OUTPUT),
    ):
        target = root / name
        target.write_text(render_export(flags, name), encoding="utf-8")
        written.append(target)
    return written


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.parse_args(argv)

    for path in write_exports():
        print(f"wrote {path.relative_to(REPO_ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
